const fs = require('fs');
const path = require('path');

const iconsDir = path.resolve(__dirname, '../src/icons');
const crestDir = path.resolve(__dirname, '../src/crest');
const outDir = path.resolve(__dirname, '../dist');
const outFile = path.join(outDir, 'Codicons.kt');

if (!fs.existsSync(outDir)) {
  fs.mkdirSync(outDir, { recursive: true });
}

function toPascalCase(str) {
  return str
    .split(/[-_]/)
    .map(part => part.charAt(0).toUpperCase() + part.slice(1))
    .join('');
}

function toCamelCase(str) {
  const pascal = toPascalCase(str);
  return pascal.charAt(0).toLowerCase() + pascal.slice(1);
}

// Branded icons that are useless or should be replaced in Crest
const BRANDED_FILTER = /^(vscode|microsoft|copilot|azure)/i;

// Collect upstream icons (excluding branded ones)
const iconList = [];
if (fs.existsSync(iconsDir)) {
  const upstreamFiles = fs.readdirSync(iconsDir).filter(f => f.endsWith('.svg'));
  for (const f of upstreamFiles) {
    const name = path.basename(f, '.svg');
    if (!BRANDED_FILTER.test(name)) {
      iconList.push({ name, filePath: path.join(iconsDir, f), isCustom: false });
    }
  }
}

// Collect Crest custom icons from src/crest/
if (fs.existsSync(crestDir)) {
  const crestFiles = fs.readdirSync(crestDir).filter(f => f.endsWith('.svg'));
  for (const f of crestFiles) {
    const name = path.basename(f, '.svg');
    iconList.push({ name, filePath: path.join(crestDir, f), isCustom: true });
  }
}

// Sort alphabetically by name
iconList.sort((a, b) => a.name.localeCompare(b.name));

let header = `// -----------------------------------------------------------------------------
// This file is automatically generated by Crest-Icons / export-to-compose.js
// Based on @vscode/codicons (Microsoft Corporation - MIT License) + Crest Custom Icons
// Do NOT edit manually; updates are synced via GitHub Actions upstream workflow.
// -----------------------------------------------------------------------------
package com.cresteditor.icons

import androidx.compose.ui.graphics.Color
import androidx.compose.ui.graphics.SolidColor
import androidx.compose.ui.graphics.vector.ImageVector
import androidx.compose.ui.graphics.vector.PathParser
import androidx.compose.ui.unit.dp

/**
 * Exact Visual Studio Code Codicons + Crest Custom Brand Icons for Jetpack Compose.
 * All official developer icons + Crest icons with lazy instantiation and memory caching.
 */
object Codicons {

    private fun create(name: String, viewportWidth: Float, viewportHeight: Float, pathData: String): ImageVector {
        val nodes = if (pathData.isNotEmpty()) {
            PathParser().parsePathString(pathData).toNodes()
        } else {
            emptyList()
        }
        return ImageVector.Builder(
            name = "Codicon.$name",
            defaultWidth = 16.dp,
            defaultHeight = 16.dp,
            viewportWidth = viewportWidth,
            viewportHeight = viewportHeight
        ).addPath(
            pathData = nodes,
            fill = SolidColor(Color.White)
        ).build()
    }
`;

let properties = '';
let mapEntries = [];

for (const item of iconList) {
  const iconName = item.name;
  const pascalName = toPascalCase(iconName);
  const camelName = toCamelCase(iconName);
  const content = fs.readFileSync(item.filePath, 'utf8');

  // Extract viewBox
  const viewBoxMatch = content.match(/viewBox="([^"]+)"/);
  let vpWidth = 16.0;
  let vpHeight = 16.0;
  if (viewBoxMatch) {
    const parts = viewBoxMatch[1].trim().split(/\s+/);
    if (parts.length === 4) {
      vpWidth = parseFloat(parts[2]) || 16.0;
      vpHeight = parseFloat(parts[3]) || 16.0;
    }
  }

  // Extract path d
  const pathMatch = content.match(/<path[^>]+d="([^"]+)"/);
  const pathData = pathMatch ? pathMatch[1] : '';

  properties += `
    private var _${camelName}: ImageVector? = null
    val ${pascalName}: ImageVector
        get() {
            if (_${camelName} != null) return _${camelName}!!
            _${camelName} = create("${pascalName}", ${vpWidth}f, ${vpHeight}f, "${pathData}")
            return _${camelName}!!
        }
`;

  mapEntries.push(`        "${iconName}" to { ${pascalName} }`);
}

// Aliases for compatibility with VS Code extensions
mapEntries.push(`        "vscode" to { Crest }`);
mapEntries.push(`        "vscode-insiders" to { Crest }`);

let lookupFunction = `
    private val allIcons: Map<String, () -> ImageVector> by lazy {
        mapOf(
${mapEntries.join(',\n')}
        )
    }

    /**
     * Resolves a Codicon by its kebab-case name (e.g. "terminal", "folder", "crest", or "$(terminal)").
     * Ideal for VS Code extensions and dynamic labels.
     */
    fun getByName(name: String): ImageVector? {
        val clean = name.trim().removePrefix("$(").removeSuffix(")").lowercase()
        return allIcons[clean]?.invoke()
    }
}
`;

fs.writeFileSync(outFile, header + properties + lookupFunction, 'utf8');
console.log(`Generated ${iconList.length} Codicons (including Crest custom icons) in ${outFile}`);
