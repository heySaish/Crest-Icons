const fs = require('fs');
const path = require('path');

const iconsDir = path.resolve(__dirname, '../src/icons');
const outDir = path.resolve(__dirname, '../dist');
const outFile = path.join(outDir, 'Codicons.kt');

if (!fs.existsSync(outDir)) {
  fs.mkdirSync(outDir, { recursive: true });
}

function toPascalCase(str) {
  return str
    .split(/[-_]/)
    .map(part => part.charAt(0).toUpperCase() + part.slice(1))
    .join('');
}

function toCamelCase(str) {
  const pascal = toPascalCase(str);
  return pascal.charAt(0).toLowerCase() + pascal.slice(1);
}

const files = fs.readdirSync(iconsDir).filter(f => f.endsWith('.svg')).sort();

let header = `// -----------------------------------------------------------------------------
// This file is automatically generated by Crest-Icons / export-to-compose.js
// Based on @vscode/codicons (Microsoft Corporation - MIT License)
// Do NOT edit manually; updates are synced via GitHub Actions upstream workflow.
// -----------------------------------------------------------------------------
package com.cresteditor.icons

import androidx.compose.ui.graphics.Color
import androidx.compose.ui.graphics.SolidColor
import androidx.compose.ui.graphics.vector.ImageVector
import androidx.compose.ui.graphics.vector.PathParser
import androidx.compose.ui.unit.dp

/**
 * Exact Visual Studio Code Codicons for Jetpack Compose.
 * All official VS Code icons with lazy instantiation and memory caching.
 */
object Codicons {

    private fun create(name: String, viewportWidth: Float, viewportHeight: Float, pathData: String): ImageVector {
        val nodes = if (pathData.isNotEmpty()) {
            PathParser().parsePathString(pathData).toNodes()
        } else {
            emptyList()
        }
        return ImageVector.Builder(
            name = "Codicon.$name",
            defaultWidth = 16.dp,
            defaultHeight = 16.dp,
            viewportWidth = viewportWidth,
            viewportHeight = viewportHeight
        ).addPath(
            pathData = nodes,
            fill = SolidColor(Color.White)
        ).build()
    }
`;

let properties = '';
let mapEntries = [];

for (const file of files) {
  const iconName = path.basename(file, '.svg');
  const pascalName = toPascalCase(iconName);
  const camelName = toCamelCase(iconName);
  const content = fs.readFileSync(path.join(iconsDir, file), 'utf8');

  // Extract viewBox
  const viewBoxMatch = content.match(/viewBox="([^"]+)"/);
  let vpWidth = 16.0;
  let vpHeight = 16.0;
  if (viewBoxMatch) {
    const parts = viewBoxMatch[1].trim().split(/\s+/);
    if (parts.length === 4) {
      vpWidth = parseFloat(parts[2]) || 16.0;
      vpHeight = parseFloat(parts[3]) || 16.0;
    }
  }

  // Extract path d
  const pathMatch = content.match(/<path[^>]+d="([^"]+)"/);
  const pathData = pathMatch ? pathMatch[1] : '';

  properties += `
    private var _${camelName}: ImageVector? = null
    val ${pascalName}: ImageVector
        get() {
            if (_${camelName} != null) return _${camelName}!!
            _${camelName} = create("${pascalName}", ${vpWidth}f, ${vpHeight}f, "${pathData}")
            return _${camelName}!!
        }
`;

  mapEntries.push(`        "${iconName}" to { ${pascalName} }`);
}

let lookupFunction = `
    private val allIcons: Map<String, () -> ImageVector> by lazy {
        mapOf(
${mapEntries.join(',\n')}
        )
    }

    /**
     * Resolves a Codicon by its kebab-case name (e.g. "terminal", "folder", or "$(terminal)").
     * Ideal for VS Code extensions and dynamic labels.
     */
    fun getByName(name: String): ImageVector? {
        val clean = name.trim().removePrefix("$(").removeSuffix(")").lowercase()
        return allIcons[clean]?.invoke()
    }
}
`;

fs.writeFileSync(outFile, header + properties + lookupFunction, 'utf8');
console.log(`Generated ${files.length} Codicons in ${outFile}`);
